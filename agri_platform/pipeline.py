from uuid import uuid4
from pathlib import Path
from .storage import read_dataset, save_layer
from .agents.profiling import profile_data
from .agents.schema import map_schema
from .agents.etl import transform_data
from .agents.validation import validate_data
from .agents.features import engineer_features
from .services import llm_schema_mapping

def run_pipeline(path, auto_repair=True):
    run_id=uuid4().hex[:10]
    logs=[]
    def log(agent,status,detail):
        logs.append({"agent":agent,"status":status,"detail":detail})
    raw=read_dataset(path)
    if raw.empty:
        raise ValueError("Uploaded dataset is empty.")
    log("Data Profiling Agent","complete",f"Profiled {len(raw)} rows and {len(raw.columns)} columns")
    profile, col_profile=profile_data(raw)
    mapping=map_schema(raw.columns)
    try:
        mapping, provider = llm_schema_mapping(raw.columns)
        log("Schema Mapping Agent", "complete", f"LLM mapping suggestions generated by {provider}")
    except Exception as exc:
        log("Schema Mapping Agent", "fallback", f"Using deterministic mapping: {str(exc)[:180]}")
    log("Schema Mapping Agent","complete",f"Generated {len(mapping)} column mapping suggestions")
    # Keep original source column names to avoid destructive or ambiguous remapping.
    cleaned,actions=transform_data(raw,auto_repair=auto_repair)
    log("ETL Generation Agent","complete",f"Prepared {len(actions)} auditable transformation actions")
    quality=validate_data(cleaned)
    log("Validation Agent","complete",f"Quality score {quality['score']:.1f}/100")
    if not all(x["passed"] for x in quality["checks"]):
        log("Validation Agent","warning","Some quality checks failed; inspect report before production use")
    silver_path=save_layer(cleaned,"silver",run_id)
    gold,feature_actions=engineer_features(cleaned)
    gold_path=save_layer(gold,"gold",run_id)
    log("Feature Engineering Agent","complete",f"Created {len(feature_actions)} domain interaction features")
    log("Storage","complete",f"Silver: {silver_path.name}; Gold: {gold_path.name}")
    return {"run_id":run_id,"profile":profile,"column_profile":col_profile,
            "mapping":mapping,"silver":cleaned,"gold":gold,"quality":quality,
            "etl_actions":actions,"feature_actions":feature_actions,"logs":logs}
